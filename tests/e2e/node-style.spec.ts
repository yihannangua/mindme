import { expect, test } from '@playwright/test'

test('多选设置字体、字号和背景，可撤销重做并刷新保留', async ({ page }) => {
  await page.goto('/')
  const a = page.getByRole('button', { name: '节点 想要探索的事', exact: true })
  const b = page.getByRole('button', { name: '节点 下一步行动', exact: true })
  const c = page.getByRole('button', { name: '节点 灵感与收集', exact: true })
  await a.click()
  await b.click({ modifiers: ['Shift'] })
  await expect(page.locator('.mind-node.selected')).toHaveCount(2)
  await page.getByLabel('字体', { exact: true }).selectOption('serif')
  await page.getByLabel('字号', { exact: true }).selectOption('28')
  await page.getByRole('button', { name: '背景色 #273b48' }).click()
  for (const node of [a, b]) {
    await expect(node.locator('text.node-label')).toHaveCSS('font-size', '28px')
    await expect(node.locator('text.node-label')).toHaveCSS('fill', 'rgb(255, 255, 255)')
    await expect(node.locator('rect').first()).toHaveCSS('fill', 'rgb(39, 59, 72)')
  }
  await expect(c.locator('text.node-label')).toHaveCSS('font-size', '14px')
  await page.getByRole('button', { name: '撤销', exact: true }).click()
  await expect(a.locator('rect').first()).not.toHaveCSS('fill', 'rgb(39, 59, 72)')
  await page.getByRole('button', { name: '重做', exact: true }).click()
  await expect(a.locator('rect').first()).toHaveCSS('fill', 'rgb(39, 59, 72)')
  await expect(page.getByText('本地已保存', { exact: true })).toBeVisible()
  await page.reload()
  await expect(a.locator('text.node-label')).toHaveCSS('font-size', '28px')
  await expect(b.locator('rect').first()).toHaveCSS('fill', 'rgb(39, 59, 72)')
  await a.dblclick()
  await expect(page.getByLabel('编辑节点文字')).toHaveCSS('font-size', '28px')
})

test('混合样式可统一设置、恢复默认，紧凑风格和中心主题均生效', async ({ page }) => {
  await page.goto('/')
  const root = page.getByRole('button', { name: '节点 我的第一个脑图', exact: true })
  const a = page.getByRole('button', { name: '节点 想要探索的事', exact: true })
  await root.click()
  await page.getByLabel('字体', { exact: true }).selectOption('mono')
  await page.getByLabel('字号', { exact: true }).selectOption('36')
  await page.getByRole('button', { name: '背景色 #fff6cb' }).click()
  await expect(root.locator('text.node-label')).toHaveCSS('fill', 'rgb(27, 41, 49)')
  await a.click({ modifiers: ['Alt'] })
  await expect(page.getByLabel('字体', { exact: true })).toHaveValue('mixed')
  await expect(page.getByLabel('字号', { exact: true })).toHaveValue('mixed')
  await page.getByLabel('字体', { exact: true }).selectOption('sans')
  await page.getByLabel('字号', { exact: true }).selectOption('18')
  await page.getByRole('button', { name: '背景色 #e3f4e9' }).click()
  await page.getByRole('button', { name: '当前画布风格：经典' }).click()
  await page.getByRole('option', { name: '紧凑', exact: true }).click()
  for (const node of [root, a]) {
    await expect(node.locator('text.node-label')).toHaveCSS('font-size', '18px')
    await expect(node.locator('rect').first()).toHaveCSS('fill', 'rgb(227, 244, 233)')
  }
  await page.getByLabel('字体', { exact: true }).selectOption('')
  await page.getByLabel('字号', { exact: true }).selectOption('')
  await page.getByRole('button', { name: '恢复默认', exact: true }).click()
  await expect(root.locator('text.node-label')).toHaveCSS('font-size', '16px')
  await expect(a.locator('text.node-label')).toHaveCSS('font-size', '11px')
})
